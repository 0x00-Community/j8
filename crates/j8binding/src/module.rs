//! Native modules and installation: [`Install`] puts a bound type somewhere (a global, a registry); [`Module`] is a
//! bound object reachable as an ES module (`import fs from "node:fs"`) and through `require`.
use alloc::format;
use alloc::string::String;
use core::fmt::Write as _;

use j8framework::{Agent, JsObject, Property};

use crate::{Glue, Member, Object};

/// The hidden global object native modules and host-internal bindings hang off (`globalThis.__j8_native`):
/// `__j8_native["node:fs"]` is a module, `__j8_native.KvStore` a binding a prelude uses.
pub const NATIVE: &str = "__j8_native";

/// A bound type that can be installed on an object (generated by `#[j8::class]` / `#[j8::object]` /
/// `#[j8::module]`).
pub trait Install {
    fn install_into<'gc>(a: &mut Agent<'gc, '_>, target: JsObject<'gc>);
}

/// A native module (generated by `#[j8::module("node:fs", "fs")]`): an object of functions under one or more
/// specifiers.
pub trait Module: Object {
    /// The specifiers it answers to (the first is its canonical name)
    const SPECIFIERS: &'static [&'static str];
}

impl Glue {
    /// The hidden native registry of this realm (created on first use)
    pub fn natives<'gc>(a: &mut Agent<'gc, '_>) -> JsObject<'gc> {
        let global = a.realm.global;
        if let Some(j8framework::Slot::Data(v)) = global.borrow().get_own(NATIVE).map(|p| p.slot)
            && let Some(o) = v.as_object()
        {
            return o;
        }
        let o = a.object();
        global.borrow_mut(a.mc).define(NATIVE, Property::hidden(o.into()));
        o
    }

    /// Installs module `M` into the native registry under each of its specifiers
    pub fn register_module<M: Module>(a: &mut Agent<'_, '_>) {
        let registry = Self::natives(a);
        let m = <M as Object>::install(a, registry);
        for spec in M::SPECIFIERS {
            registry.borrow_mut(a.mc).define(spec, Property::hidden(m.into()));
        }
    }

    /// The ES module source standing for module `M` when `spec` is one of its specifiers: a default export (the
    /// object) and one named export per member
    pub fn module_source<M: Module>(spec: &str) -> Option<String> {
        let canonical = M::SPECIFIERS.first()?;
        if !M::SPECIFIERS.contains(&spec) {
            return None;
        }
        let mut out = format!("const m = globalThis.{NATIVE}[\"{canonical}\"];\nexport default m;\n");
        for member in M::MEMBERS {
            let name = match member {
                Member::Method { name, .. } | Member::Static { name, .. } | Member::Accessor { name, .. } => name,
            };
            let _ = writeln!(out, "export const {name} = m.{name};");
        }
        Some(out)
    }
}
