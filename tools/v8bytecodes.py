#!/usr/bin/env python3
"""Generates crates/j8bytecode/v8.json from V8's interpreter headers: the bytecode list (V8's numbering), every
bytecode's implicit accumulator use and operand types, and the operand types with their size class.

    tools/v8bytecodes.py <v8 checkout> > crates/j8bytecode/v8.json
"""
import json
import re
import sys


def macros(text):
    """`#define NAME(args) body` (continuation lines joined) ⇒ {NAME: body}"""
    text = text.replace('\\\n', ' ')
    out = {}
    for m in re.finditer(r'^#define\s+(\w+)\(([^)]*)\)\s*(.*)$', text, re.M):
        out[m.group(1)] = m.group(3)
    return out


def calls(body):
    """Top-level `NAME(args)` calls in a macro body, in order"""
    body = re.sub(r'/\*.*?\*/', ' ', body)
    i, out = 0, []
    while i < len(body):
        m = re.compile(r'(\w+)\s*\(').match(body, i)
        if not m:
            i += 1
            continue
        depth, j = 1, m.end()
        while depth:
            depth += {'(': 1, ')': -1}.get(body[j], 0)
            j += 1
        out.append((m.group(1), body[m.end():j - 1]))
        i = j
    return out


def expand(defs, name):
    """The `V(...)` / `V_TSA(...)` entries of list macro `name`, nested lists expanded"""
    out = []
    for callee, args in calls(defs[name]):
        if callee in ('V', 'V_TSA'):
            out.append([a.strip() for a in args.split(',')])
        elif callee in defs:
            out.extend(expand(defs, callee))
    return out


def main(root):
    b = macros(open(f'{root}/src/interpreter/bytecodes.h').read())
    o = macros(open(f'{root}/src/interpreter/bytecode-operands.h').read())
    version = dict(re.findall(r'#define V8_(MAJOR_VERSION|MINOR_VERSION|BUILD_NUMBER|PATCH_LEVEL)\s+(\d+)', open(f'{root}/include/v8-version.h').read()))
    operand_types = [{'name': n, 'info': i.split('::k')[1]} for n, i in expand(o, 'OPERAND_TYPE_LIST')]
    bytecodes = []
    for entry in expand(b, 'BYTECODE_LIST'):
        name, use, *ops = entry
        bytecodes.append({'name': name, 'use': use.split('::k')[1], 'operands': [op.split('::k')[1] for op in ops]})
    raw = [(n, v) for n, v in re.findall(r'^\s*k(\w+)\s*=\s*([^,\n]+),?\s*$', open(f'{root}/src/interpreter/bytecode-operands.h').read().split('enum class ImplicitRegisterUse')[1].split('};')[0], re.M)]
    bits = {}
    for n, v in raw:
        bits[n] = eval(re.sub(r'k(\w+)', lambda m: str(bits[m.group(1)]), v))
    uses = [{'name': n, 'bits': bits[n]} for n, _ in raw]
    json.dump({
        'source': f"V8 {version['MAJOR_VERSION']}.{version['MINOR_VERSION']}.{version['BUILD_NUMBER']} src/interpreter/bytecodes.h + bytecode-operands.h (generated by tools/v8bytecodes.py)",
        'implicit_register_use': uses,
        'operand_types': operand_types,
        'bytecodes': bytecodes,
    }, sys.stdout, indent=1)
    sys.stdout.write('\n')


main(sys.argv[1])
